def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fonts", type=Path, default=Path("C:/Windows/Fonts"))
    parser.add_argument("--output", type=Path, default=ROOT / "output/pdf" / NAME)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    build(args.output, args.fonts)
    bundled = GUIDE / NAME
    if args.output.resolve() != bundled.resolve():
        shutil.copyfile(args.output, bundled)
    print(json.dumps({"pdf": str(args.output), "bundled_copy": str(bundled), "bytes": args.output.stat().st_size, "pages": 20}, ensure_ascii=False))


if __name__ == "__main__":
    main()
