class Manual:
    def __init__(self, destination, fonts):
        for name, file in (("Guide", "segoeui.ttf"), ("GuideBold", "segoeuib.ttf")):
            pdfmetrics.registerFont(TTFont(name, str(fonts / file)))
        pdfmetrics.registerFontFamily("Guide", normal="Guide", bold="GuideBold", italic="Guide", boldItalic="GuideBold")
        self.c = canvas.Canvas(str(destination), pagesize=(WIDTH, HEIGHT), pageCompression=1)
        self.c.setTitle("Document Forensic Inspector - руководство пользователя")
        self.c.setAuthor("Document Forensic Inspector / учебные материалы проекта")
        self.c.setSubject(f"Иллюстрированное руководство, {VERSION}, {DATE}")
        self.c.setViewerPreference("DisplayDocTitle", "true")
        self.page = 0
        self.audit = []

    def para(self, text, x, top, width, size=11, color=INK, bold=False, max_height=None):
        text = text.replace("—", "-").replace("–", "-").replace("\u2011", "-")
        style = ParagraphStyle("body", fontName="GuideBold" if bold else "Guide", fontSize=size, leading=size * 1.36, textColor=color, alignment=TA_LEFT, splitLongWords=True)
        p = Paragraph(text, style)
        _, height = p.wrap(width, 1000)
        if max_height is not None and height > max_height + .1:
            raise ValueError(f"Page {self.page}: text exceeds allocated height: {text[:75]}")
        if top + height > HEIGHT - 37:
            raise ValueError(f"Page {self.page}: text runs into footer: {text[:75]}")
        p.drawOn(self.c, x, HEIGHT - top - height)
        self.audit.append({"page": self.page, "type": "text", "box": [x, top, width, height]})
        return top + height

    def start(self, title, section="Руководство пользователя", key=None):
        if self.page:
            self.footer()
            self.c.showPage()
        self.page += 1
        self.c.setFillColor(colors.white)
        self.c.rect(0, 0, WIDTH, HEIGHT, fill=1, stroke=0)
        self.para(section, MARGIN, 19, CONTENT, 9, ACCENT)
        self.para(title, MARGIN, 42, CONTENT, 25, bold=True)
        if key:
            self.c.bookmarkPage(key)
            self.c.addOutlineEntry(title, key, level=0)

    def footer(self):
        self.c.setStrokeColor(LINE)
        self.c.line(MARGIN, 32, WIDTH - MARGIN, 32)
        self.c.setFillColor(MUTED)
        self.c.setFont("Guide", 8)
        self.c.drawString(MARGIN, 18, "Document Forensic Inspector  |  АНСЭ 0.5.1  |  09.10.2026")
        self.c.drawRightString(WIDTH - MARGIN, 18, str(self.page))

    def shot(self, name, x=MARGIN, top=124, width=CONTENT, height=398, align="center"):
        source = GUIDE / "screenshots" / f"{name}.png"
        reader = ImageReader(str(source))
        iw, ih = reader.getSize()
        scale = min(width / iw, height / ih)
        w, h = iw * scale, ih * scale
        left = x + (width - w) / 2 if align == "center" else x
        self.c.drawImage(reader, left, HEIGHT - top - h, w, h, mask="auto")
        self.c.setStrokeColor(LINE)
        self.c.setLineWidth(.6)
        self.c.rect(left, HEIGHT - top - h, w, h, fill=0, stroke=1)
        self.audit.append({"page": self.page, "type": "screenshot", "source": source.name, "box": [left, top, w, h], "pixels_to_points": scale})
        return top + h

    def screen_page(self, title, key, image, instruction, caption):
        self.start(title, key=key)
        self.para(instruction, MARGIN, 89, CONTENT, 11, max_height=31)
        self.shot(image)
        self.para(caption, MARGIN, 530, CONTENT, 9.2, MUTED, max_height=27)

    def steps(self, items, x, top, width, size=11, gap=14, start_index=1):
        y = top
        for i, (label, detail) in enumerate(items, start_index):
            self.para(f"{i}.", x, y, 23, size + 1, ACCENT, True)
            y = self.para(f"<b>{label}</b><br/>{detail}", x + 28, y, width - 28, size) + gap
        return y

    def table(self, headers, rows, widths, top, x=MARGIN, size=10.3):
        y = top
        for ri, row in enumerate([headers] + rows):
            paragraphs = []
            for text, width in zip(row, widths):
                style = ParagraphStyle("cell", fontName="GuideBold" if ri == 0 else "Guide", fontSize=size, leading=size * 1.34, textColor=colors.white if ri == 0 else INK)
                p = Paragraph(text.replace("—", "-").replace("–", "-"), style)
                _, h = p.wrap(width - 20, 1000)
                paragraphs.append((p, h))
            height = max(h for _, h in paragraphs) + 20
            if y + height > HEIGHT - 42:
                raise ValueError(f"Table exceeds page {self.page}")
            self.c.setFillColor(ACCENT if ri == 0 else PALE if ri % 2 else colors.white)
            self.c.rect(x, HEIGHT - y - height, sum(widths), height, fill=1, stroke=0)
            colx = x
            for (p, h), width in zip(paragraphs, widths):
                p.drawOn(self.c, colx + 10, HEIGHT - y - 10 - h)
                colx += width
            y += height
            self.c.setStrokeColor(LINE)
            self.c.line(x, HEIGHT - y, x + sum(widths), HEIGHT - y)
        self.audit.append({"page": self.page, "type": "table", "box": [x, top, sum(widths), y - top]})
        return y

    def finish(self, output):
        self.footer()
        self.c.save()
        (output.parent / "user-guide-layout.json").write_text(json.dumps({"pages": self.page, "elements": self.audit}, ensure_ascii=False, indent=2), encoding="utf-8")


