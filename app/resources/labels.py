def parameter_label(name: str) -> str:
    if name in NAME_LABELS:
        return NAME_LABELS[name]
    match = re.fullmatch(r"Signature (\d+) (.+)", name)
    if match:
        suffix = {
            "ByteRange layout": "структура ByteRange",
            "cryptographic integrity": "криптографическая целостность",
        }.get(match.group(2), match.group(2))
        return f"Подпись {match.group(1)}: {suffix}"
    if name.startswith("Different values: "):
        return "Различаются значения поля: " + name.removeprefix("Different values: ")
    if name.startswith("Indirect objects with a stream —"):
        suffix = name.split("—", 1)[1].strip()
        return f"Объекты со stream: {suffix}"
    return name


def parameter_description(name: str, supplied: str = "") -> str:
    known = DESCRIPTIONS.get(name)
    if known and supplied and supplied != known:
        return known + "\n" + supplied
    return known or supplied or "Техническое значение; источник указан в соседнем столбце."


