"""Explain observations, possible causes and next checks without deciding for an expert."""

from __future__ import annotations

from dataclasses import dataclass

from app.analyzers.interpretation import RULESET_VERSION, quoted
from app.analyzers.timeline import _is_date_field, normalize_date
from app.models import Finding
from app.resources.labels import parameter_description, parameter_label


@dataclass(frozen=True, slots=True)
class Guidance:
    meaning: str
    attention: str
    alternatives: str
    check: str
    rule: str

    def text(self) -> str:
        return "\n\n".join(
            (
                "Что означает\n" + self.meaning,
                "На что обратить внимание\n" + self.attention,
                "Возможные объяснения и пределы\n" + self.alternatives,
                "Что проверить дальше\n" + self.check,
            )
        )


def explain_finding(f: Finding) -> Guidance:
    name = f.name.casefold().lstrip("/")
    if f.source.startswith("ExifTool/System"):
        return Guidance(
            "Это свойство файловой системы рабочей копии, с которой запущен ExifTool.",
            "Не переносите время создания или доступа к рабочей копии в хронологию происхождения документа.",
            "Копирование и сам анализ могут менять служебные даты экземпляра; это не изменение содержания документа.",
            "Сопоставить с отдельно сохранёнными датами оригинала и обстоятельствами получения носителя.",
            "working-copy-filesystem",
        )
    if f.category == "Tool diagnostics":
        return Guidance(
            "Это сообщение о ходе проверки, а не свойство исследуемого содержания.",
            "Определить, какие сведения не получены и влияет ли это на поставленный вопрос.",
            "Отсутствие утилиты, ошибка или тайм-аут не означают отсутствия артефакта и сами по себе не образуют НПВ.",
            "Открыть журнал запуска, проверить доступность метода и повторить нужную проверку либо выбрать другой метод.",
            "diagnostic",
        )
    if f.conflict or f.category == "Metadata conflicts":
        return Guidance(
            "Правило сопоставления обнаружило различие записей или их представлений.",
            "Проверьте, относятся ли значения к одному полю, событию, объекту и версии. Различие не равно подделке.",
            "Возможны разные часовые пояса, устаревший XMP, перенос метаданных, разные этапы сохранения или трактовка парсерами.",
            "Открыть обе исходные записи и их расположение; даты с известным поясом сравнить в UTC, неизвестный пояс не угадывать.",
            "metadata-discrepancy",
        )
    if _is_date_field(f.name) or name == "historywhen":
        parsed = normalize_date(str(f.value))
        timing = (
            "Значение не удалось разобрать как календарную дату; последовательность событий по нему не определяется."
            if not parsed.get("parsed")
            else "В самом поле пояс не записан; проверьте отдельный OffsetTime/OffsetTimeOriginal. "
            "Хронология связывает однозначную пару полей одного EXIF-источника; без такой пары абсолютный порядок не установлен."
            if not parsed.get("timezone_present")
            else "Часовой пояс указан; нормализация в UTC позволяет сопоставить записи, но не подтверждает часы устройства."
        )
        event = (
            "Это заявленное время съёмки в метаданных."
            if "original" in name
            else "Это заявленное время изменения метаданных, а не обязательно содержимого."
            if "metadata" in name
            else "Это заявленная дата создания документа или объекта."
            if "creat" in name
            else "Это заявленная дата изменения документа или объекта."
            if "mod" in name
            else "Это временная запись; её смысл определяется конкретным полем и источником."
        )
        return Guidance(
            event,
            timing,
            "Дату можно изменить; она может быть унаследована от исходника. Разные события не обязаны иметь одинаковую дату.",
            "В хронологии выбрать две записи для сопоставления; проверить точность, пояс, источник и независимые журналы.",
            "date",
        )
    if name in {"author", "artist", "lastmodifiedby", "ownername", "by-line"} or (
        name == "creator" and f.category in {"OOXML Core Properties", "XMP"}
    ):
        return Guidance(
            "Записанное имя автора, редактора или учётной записи. Факт чтения поля не идентифицирует человека.",
            "Сопоставьте имя с комментариями, исправлениями и другими версиями; совпадение только внутри файла не независимо.",
            "Имя может происходить из шаблона, настроек приложения, общего профиля или быть изменено вручную.",
            "Проверить сведения об учётных записях, исходных носителях и истории хранения.",
            "declared-person",
        )
    if name in {
        "software",
        "producer",
        "creatortool",
        "application",
        "encoder",
        "historysoftwareagent",
    } or (name == "creator" and f.category == "PDF Info"):
        return Guidance(
            "Обозначение программы, записанное в метаданных при одном из этапов обработки.",
            "Разные Creator и Producer могут описывать создание и преобразование, а не противоречие.",
            "Название редактора не доказывает монтаж. Поле могло сохраниться после обработки другой программой или копирования.",
            "Сопоставить с особенностями структуры, XMP History, ревизиями и контрольными образцами этой программы.",
            "software",
        )
    if f.category == "GPS":
        return Guidance(
            "Запись геопозиционирования: координата, направление, время или служебный параметр GPS.",
            "Для положения нужны совместимые широта и долгота, направления N/S и E/W и система отсчёта. Ноль — допустимое значение.",
            "Редактируемая GPS-запись не подтверждает место фактической съёмки. GPS-время и локальное EXIF-время имеют разные основания.",
            "Проверить полный набор тегов и сопоставить изображённую обстановку с независимыми материалами.",
            "gps",
        )
    if (
        name in {"tracked changes", "tracked changes count", "word comments"}
        or "comment" in f.category.casefold()
    ):
        return Guidance(
            "Сохранённые записи комментариев или исправлений, включая заявленные имена и даты, если они есть.",
            "Ищите связанные фрагменты текста, авторов записей, даты и расположение в частях контейнера.",
            "Принятые или удалённые исправления могут исчезнуть. Отсутствие записей не исключает редактирование; их имена не доказывают личность.",
            "Сопоставить текст с предыдущими версиями; для дат записей учитывать пояс и независимость источников.",
            "review-history",
        )
    if (
        "incremental" in name
        or "revision" in name
        or name in {"eof markers", "startxref markers", "prev references"}
    ):
        return Guidance(
            parameter_description(f.name, f.description),
            "Сначала отличите подсчёт маркеров от подтверждённой цепочки ревизий. Затем определите, какие объекты и страницы различаются.",
            "Дополнительное сохранение может добавлять подпись, форму или служебные данные; оно не обязательно меняет видимое содержание. "
            "Маркер внутри потока может не быть границей ревизии.",
            "Сопоставить xref и /Prev, извлечённые ревизии, метаданные и визуальные различия страниц.",
            "pdf-revisions",
        )
    if ("signature" in name and f.category != "Integrity") or "byterange" in name:
        return Guidance(
            parameter_description(f.name, f.description),
            "Разделите наличие контейнера подписи, покрытие байтов, криптографическую целостность и доверие сертификату.",
            "Наличие подписи не означает успешной проверки. Криптографическая целостность сама по себе не подтверждает доверие, время подписания или полномочия подписанта.",
            "Проверить покрытие ByteRange, цепочку и статус сертификатов, отметку времени и изменения после подписания.",
            "signature",
        )
    if "javascript" in name or name in {
        "open actions",
        "launch actions",
        "additional actions",
        "macro parts",
    }:
        return Guidance(
            parameter_description(f.name, f.description),
            "Уточните, найден ли только текстовый маркер, ссылка на объект или реальная часть с кодом. Счётчики не равны фактам выполнения.",
            "Сценарий может обслуживать форму или автоматизацию. Наличие кода не доказывает вредоносность или факт его запуска.",
            "Исследовать структуру и содержимое без выполнения; связать наблюдение с конкретным вопросом экспертизы.",
            "active-content",
        )
    if "hidden" in name or name in {
        "embedded files",
        "embeddings",
        "external relationships",
        "unsafe archive paths",
    }:
        return Guidance(
            parameter_description(f.name, f.description),
            "Проверьте конкретные части, их типы, пути, связи и доступность в обычном просмотре.",
            "Скрытие листа, вложение или внешняя связь могут быть штатной частью документа. Ссылка не доказывает обращение к её адресу.",
            "Зафиксировать расположение и идентификатор объекта, сравнить с отображаемым содержимым и предыдущими версиями.",
            "hidden-linked-content",
        )
    if name in {
        "documentid",
        "instanceid",
        "originaldocumentid",
        "trailer document ids",
        "xmp document lineage",
        "document id changed across trailers",
        "xmp editing history",
    }:
        return Guidance(
            parameter_description(f.name, f.description),
            "Сопоставьте идентификаторы экземпляров, связь с исходником и заявленную историю между файлами или ревизиями.",
            "Идентификатор не является контрольной суммой. Он может копироваться, регенерироваться или редактироваться; совпадение не доказывает тождество байтов.",
            "Подтвердить связь сравнением содержимого, хешей, структуры и внешней истории хранения.",
            "lineage",
        )
    if f.category == "Integrity":
        return Guidance(
            parameter_description(f.name, f.description),
            "Укажите, какие именно экземпляры, байты и моменты проверялись. Распознавание формата и совпадение хешей решают разные задачи.",
            "Контрольная сумма не доказывает подлинность содержания и отсутствие изменений до получения материала. Неудачное чтение не равно изменению.",
            "Сохранить хеши, сведения об оригинале, рабочей копии и результаты повторного чтения.",
            "integrity",
        )
    if any(term in name for term in ("validation", "conformance", "jhove", "verapdf")):
        return Guidance(
            parameter_description(f.name, f.description),
            "Уточните профиль, версию валидатора и конкретное нарушенное правило.",
            "Соответствие стандарту описывает структуру, а не подлинность. Ошибка может быть следствием особенностей генератора, повреждения или ограничения валидатора.",
            "Проверить точное сообщение и объект ошибки; при необходимости сопоставить с независимым парсером.",
            "format-validation",
        )
    if name in {
        "make",
        "model",
        "lensmodel",
        "lensmake",
        "bodyserialnumber",
        "serialnumber",
        "cameraserialnumber",
    }:
        return Guidance(
            "Заявленные сведения об устройстве или оптике, записанные в метаданных.",
            "Модель описывает тип устройства; серийный номер потенциально связывает экземпляры, но требует проверки источника.",
            "Поля можно редактировать или переносить вместе с изображением. Они не устанавливают владельца устройства.",
            "Сопоставить с исходными файлами с предполагаемого устройства, MakerNotes и независимыми сведениями.",
            "capture-device",
        )
    if name in {
        "exposuretime",
        "fnumber",
        "iso",
        "isospeedratings",
        "focallength",
        "flash",
        "whitebalance",
        "orientation",
    }:
        return Guidance(
            "Параметр съёмки или отображения изображения. ExposureTime — длительность экспозиции, а не календарная дата.",
            "Оцените единицы, дробные значения и совместимость с другими параметрами камеры. Orientation задаёт способ отображения.",
            "Параметры могут сохраняться после редактирования; сами по себе не доказывают условия съёмки или отсутствие обработки.",
            "Сопоставить полный EXIF с изображением и контрольными файлами; не помещать длительности в календарную хронологию.",
            "capture-settings",
        )
    if any(
        term in name
        for term in ("width", "height", "resolution", "colorspace", "colourspace")
    ) or name in {"color mode", "bitdepth", "bitspersample", "icc_profile"}:
        return Guidance(
            "Геометрия, цветовое представление или профиль изображения. Размер в пикселях отличается от разрешения для печати.",
            "Сопоставьте размеры встроенного изображения, предпросмотра и основного содержимого; не смешивайте их.",
            "Различия могут возникать при масштабировании, экспорте или создании миниатюры. Они не доказывают монтаж.",
            "Проверить принадлежность параметра конкретному изображению или потоку, его единицы и соответствие декодированным данным.",
            "image-representation",
        )
    if any(
        term in name
        for term in (
            "codec",
            "bit_rate",
            "bitrate",
            "sample_rate",
            "framerate",
            "frame_rate",
            "duration",
        )
    ):
        return Guidance(
            "Параметр кодирования или длительность медиапотока. Длительность не является временем создания файла.",
            "Разделяйте сведения контейнера и отдельных аудио/видеопотоков; у потоков могут различаться длительности и временные базы.",
            "Расхождение может объясняться переменной частотой кадров, смещением начала, округлением, монтажом или повреждением; одна цифра причину не устанавливает.",
            "Проверить единицы, time_base, start_time и каждый поток; сопоставить декодирование с исходными версиями.",
            "media-stream",
        )
    known = parameter_description(f.name, f.description)
    return Guidance(
        known
        if not known.startswith("Техническое значение;")
        else "Анализатор вернул техническое поле. Специализированное толкование этого параметра пока не описано.",
        "Оценивать значение вместе с единицами измерения, типом объекта, источником и расположением.",
        "Это описание поля, а не самостоятельный признак вмешательства. Без контекста причинный вывод не формулируется.",
        "Сверить смысл параметра с документацией указанного анализатора; зафиксировать связь с поставленным вопросом.",
        "technical-field",
    )


def observation_draft(f: Finding) -> str:
    guide = explain_finding(f)
    return "\n\n".join(
        (
            "ЗАГОТОВКА ОПИСАНИЯ НАБЛЮДЕНИЯ — проверить перед включением в исследовательскую часть",
            f"При анализе средством «{f.source}» получено значение поля «{parameter_label(f.name)}» "
            f"({f.name}): {quoted(f.value, 2000)}.",
            f"Расположение: {f.location or f.category}. Идентификатор записи: {f.id}.",
            f"Пределы интерпретации: {guide.alternatives}",
            f"Для проверки: {guide.check}",
            f"Правило пояснения: {guide.rule}; {RULESET_VERSION}.",
        )
    )
